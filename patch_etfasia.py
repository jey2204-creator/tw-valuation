#!/usr/bin/env python3
"""2026-11-22 20:23 📦 ETF「國外」改名「美國」＋新增「日本」「韓國」「中國」三類（世杰選方案 ①；韓國照 3 檔）。
名單在 fetch_rank.py 的 ETF_THEME（日本 00955 00949 00951 00645 00661；韓國 00735 009829 009833；中國 00882 00887 00752 00877 006205），共 51 檔。
這支只改首頁顯示：分組 emoji（美國🇺🇸 日本🇯🇵 韓國🇰🇷 中國🇨🇳）、選美國時沿用原「國外 ETF」時差提醒、選日本/韓國/中國時的提醒、描述與頁尾類別順序。
用法：python3 patch_etfasia.py       → beta_etfj.html（獨立檔名，避免跟其他對話的 beta.html 互蓋）
      python3 patch_etfasia.py prod  → index.html
頁尾版本用正規式換成 v1122t；其餘錨點都要剛好出現一次。
"""
import re, sys
prod = len(sys.argv) > 1 and sys.argv[1] == 'prod'

E = [
    ("EM={'市值':'🏛️','高息':'💰','科技':'💻','債券':'🏦','國外':'🌏','主動':'🎯','槓桿':'⚡'}",
     "EM={'市值':'🏛️','高息':'💰','科技':'💻','債券':'🏦','國外':'🌏','美國':'🇺🇸','日本':'🇯🇵','韓國':'🇰🇷','中國':'🇨🇳','主動':'🎯','槓桿':'⚡'}"),
    ("${ETC==='國外'?'<br>🌏 <b>國外 ETF",
     "${ETC==='日本'||ETC==='韓國'?`<br>${ETC==='日本'?'🇯🇵':'🇰🇷'} <b>${ETC} ETF 規模都很小 (最大不到 100 億)</b>：成交量少、買賣價差和折溢價較大，下單前看一下折溢價；日韓收盤時間跟台股接近，同一天的漲跌可以直接比，但還有匯率 (${ETC==='日本'?'日圓':'韓元'}) 影響。${ETC==='韓國'?'00735 是台股＋韓股各半；009833 剛上市、規模不到 5 億，流動性差。':''}`:''}"
     "${ETC==='中國'?'<br>🇨🇳 <b>中國 ETF 受政策影響大</b>：跟台股、美股的連動低，波動來源不同；00882 是港股高股息、006205 是上證 A 股，性質不一樣。':''}"
     "${ETC==='國外'||ETC==='美國'?'<br>🌏 <b>國外 ETF"),
    ("市值→高息→科技→債券→國外→主動→槓桿)", "市值→高息→科技→債券→美國→日本→韓國→中國→主動→槓桿)"),
    ("desc:'台股掛牌 ETF 各類規模前 5 大 (市值型、高股息、科技/半導體、債券、國外、主動式、槓桿)＋00713、00940、00892'",
     "desc:'台股掛牌 ETF 各類規模前 5 大 (市值型、高股息、科技/半導體、債券、美國、日本、韓國、中國、主動式、槓桿)＋00713、00940、00892'"),
]

s = open('index.html', encoding='utf-8').read()
for a, b in E:
    assert s.count(a) == 1, (s.count(a), a[:60])
    s = s.replace(a, b)
s, nv = re.subn(r'<span style="opacity:\.5">v1122[a-z]</span>', '<span style="opacity:.5">v1122t</span>', s)
assert nv == 1, nv
if not prod:
    s = s.replace('<title>', '<title>[beta] ', 1)
dst = 'index.html' if prod else 'beta_etfj.html'
open(dst, 'w', encoding='utf-8').write(s)
print('ok', dst)
